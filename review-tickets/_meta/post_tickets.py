#!/usr/bin/env python3
"""Post the review tickets in this directory to a GitHub repository with the GitHub CLI (`gh`).

Run it from a machine where `gh auth status` shows an account with write access to the repository:

    python3 review-tickets/_meta/post_tickets.py                  # dry run: print the plan, post nothing
    python3 review-tickets/_meta/post_tickets.py --yes            # post every ticket
    python3 review-tickets/_meta/post_tickets.py --yes --only FIX-104 FIX-105   # post a subset

What it does, in order:
  1. Reads every DEC-*.md / FIX-*.md / FEAT-*.md beside README.md (front matter + body).
  2. Creates any label the tickets use that the repository lacks (e.g. "review: 2026-11-27").
  3. Creates one issue per ticket, FIX first, then FEAT, then DEC, each in ID order. It records
     ID -> issue number in posted.json next to this script.
  4. Edits each posted issue once, so every mention of another ticket ID reads "FIX-107 (#123)".

It is resumable: an ID already in posted.json is never created again, so after an interruption
rerun the same command. Statuses: tickets with `status: DROP` are skipped.
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
TICKETS = HERE.parent  # review-tickets/
STATE = HERE / "posted.json"
ID_RE = re.compile(r"\b((?:DEC|FIX|FEAT)-\d{3})\b")
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not m:
        sys.exit(f"{path.name}: no front matter")
    fm = {}
    for line in m.group(1).splitlines():
        line = re.sub(r"\s+#.*$", "", line)
        if ":" in line:
            k, v = line.split(":", 1)
            v = v.strip()
            fm[k.strip()] = json.loads(v) if v[:1] in '["{' else v
    return fm, m.group(2).strip() + "\n"


def order_key(tid):
    prefix, n = tid.split("-")
    return ({"FIX": 0, "FEAT": 1, "DEC": 2}[prefix], int(n))


def gh(*args, capture=True):
    result = subprocess.run(["gh", *args], capture_output=capture, text=True)
    if result.returncode != 0:
        sys.exit(f"gh {' '.join(args[:3])} … failed:\n{result.stderr}")
    return result.stdout


def linked(body, own_id, numbers):
    def sub(m):
        tid = m.group(1)
        if tid == own_id or tid not in numbers:
            return tid
        return f"{tid} (#{numbers[tid]})"
    # Do not touch an ID that already carries its number from an earlier run.
    return re.sub(r"\b((?:DEC|FIX|FEAT)-\d{3})\b(?! \(#\d+\))", sub, body)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default="thekaveh/NNx")
    ap.add_argument("--yes", action="store_true", help="actually post (default: dry run)")
    ap.add_argument("--only", nargs="*", help="ticket IDs to post (default: all)")
    ap.add_argument("--no-footer", action="store_true", help="omit the generated-by footer")
    args = ap.parse_args()

    tickets = {}
    for path in sorted(TICKETS.glob("*.md")):
        if ID_RE.fullmatch(path.stem):
            fm, body = parse(path)
            if fm.get("status") != "DROP":
                tickets[fm["id"]] = (fm, body)
    ids = sorted(tickets, key=order_key)
    if args.only:
        unknown = set(args.only) - set(tickets)
        if unknown:
            sys.exit(f"unknown IDs: {sorted(unknown)}")
        ids = [i for i in ids if i in args.only]
    numbers = json.loads(STATE.read_text()) if STATE.exists() else {}
    labels = sorted({label for fm, _ in tickets.values() for label in fm["labels"]})

    print(f"{len(ids)} tickets to post to {args.repo}; {len([i for i in ids if i in numbers])} already posted.")
    if not args.yes:
        for tid in ids:
            fm, _ = tickets[tid]
            state = f"#{numbers[tid]}" if tid in numbers else "new"
            print(f"  {state:>6}  {fm['title']}  [{', '.join(fm['labels'])}]")
        print("Dry run only. Rerun with --yes to post.")
        return

    existing = {json.loads(line)["name"] for line in gh("label", "list", "--repo", args.repo, "--limit", "500",
                                                       "--json", "name", "--jq", ".[] | tostring").splitlines()}
    for label in labels:
        if label not in existing:
            print(f"creating label {label!r}")
            gh("label", "create", label, "--repo", args.repo, "--color", "ededed")

    footer = "" if args.no_footer else FOOTER
    for tid in ids:  # pass 1: create
        if tid in numbers:
            continue
        fm, body = tickets[tid]
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as handle:
            handle.write(linked(body, tid, numbers) + footer)
        cmd = ["issue", "create", "--repo", args.repo, "--title", fm["title"], "--body-file", handle.name]
        for label in fm["labels"]:
            cmd += ["--label", label]
        url = gh(*cmd).strip().splitlines()[-1]
        numbers[tid] = int(url.rstrip("/").rsplit("/", 1)[-1])
        STATE.write_text(json.dumps(numbers, indent=1, sort_keys=True))
        print(f"{tid} -> #{numbers[tid]}")

    for tid in ids:  # pass 2: link every cross-reference to its issue number
        fm, body = tickets[tid]
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as handle:
            handle.write(linked(body, tid, numbers) + footer)
        gh("issue", "edit", str(numbers[tid]), "--repo", args.repo, "--body-file", handle.name)
    print(f"done: {len(ids)} issues posted and linked; numbers saved in {STATE}")


if __name__ == "__main__":
    main()
